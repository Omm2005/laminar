// Copies HANDOFF/00-glossary-and-notation.md into convex/glossary.ts, so the assistant (agent.ts, search_glossary)
// can search it: the Convex backend can't read repo files at run time. Run after editing the glossary, then deploy:
//     npm run glossary
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "..", "..", "HANDOFF", "00-glossary-and-notation.md");
const out = join(here, "..", "convex", "glossary.ts");
const md = readFileSync(src, "utf8");
writeFileSync(out,
  "// GENERATED by scripts/sync-glossary.mjs from HANDOFF/00-glossary-and-notation.md: edit that file, then\n" +
  "// `npm run glossary` and deploy. The assistant searches it (agent.ts, search_glossary).\n" +
  `export const GLOSSARY_MD = ${JSON.stringify(md)};\n`);
console.log(`convex/glossary.ts: ${md.length} characters from ${src}`);
